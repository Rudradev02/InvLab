from core.num_to_words import amount_to_words_inr


class InvoiceNumberedCanvas(canvas.Canvas):
    """Canvas wrapper to print page numbers and tax invoice disclaimer."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        page_count = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(page_count)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 7)
        self.setFillColor(colors.HexColor("#64748B"))
        # Top banner line
        self.setStrokeColor(colors.HexColor("#CBD5E1"))
        self.setLineWidth(0.5)
        self.line(36, self._pagesize[1] - 25, self._pagesize[0] - 36, self._pagesize[1] - 25)

        # Footer
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(self._pagesize[0] - 36, 18, page_text)
        disclaimer = "Tax Invoice • This invoice is generated by InvLab. Formatting is not a certified tax filing tool."
        self.drawString(36, 18, disclaimer)
        self.restoreState()


def generate_invoice_pdf(sale) -> bytes:
    """
    Generates a professional GST Tax Invoice PDF.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=36,
        rightMargin=36,
        topMargin=36,
        bottomMargin=36,
    )

    biz_settings = BusinessSettings.get_settings()
    customer = sale.customer
    is_interstate = sale.is_interstate

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "InvTitle",
        parent=styles["Heading1"],
        fontSize=18,
        leading=22,
        textColor=colors.HexColor("#0F172A"),
        fontName="Helvetica-Bold",
        alignment=2,  # Right align
    )
    subtitle_style = ParagraphStyle(
        "InvSubtitle",
        parent=styles["Normal"],
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#475569"),
        fontName="Helvetica",
        alignment=2,
    )
    company_name_style = ParagraphStyle(
        "CompanyName",
        parent=styles["Heading2"],
        fontSize=13,
        leading=16,
        textColor=colors.HexColor("#1E3A8A"),
        fontName="Helvetica-Bold",
    )
    meta_label = ParagraphStyle(
        "MetaLabel",
        parent=styles["Normal"],
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#475569"),
        fontName="Helvetica-Bold",
    )
    meta_val = ParagraphStyle(
        "MetaVal",
        parent=styles["Normal"],
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#0F172A"),
        fontName="Helvetica",
    )
    table_header = ParagraphStyle(
        "TableHeader",
        parent=styles["Normal"],
        fontSize=7.5,
        leading=9.5,
        textColor=colors.white,
        fontName="Helvetica-Bold",
        alignment=1,
    )
    table_cell = ParagraphStyle(
        "TableCell",
        parent=styles["Normal"],
        fontSize=7.5,
        leading=9.5,
        textColor=colors.HexColor("#1E293B"),
        fontName="Helvetica",
    )
    table_cell_bold = ParagraphStyle(
        "TableCellBold",
        parent=styles["Normal"],
        fontSize=7.5,
        leading=9.5,
        textColor=colors.HexColor("#0F172A"),
        fontName="Helvetica-Bold",
    )
    table_cell_right = ParagraphStyle(
        "TableCellRight",
        parent=styles["Normal"],
        fontSize=7.5,
        leading=9.5,
        textColor=colors.HexColor("#1E293B"),
        fontName="Helvetica",
        alignment=2,
    )
    table_cell_right_bold = ParagraphStyle(
        "TableCellRightBold",
        parent=styles["Normal"],
        fontSize=7.5,
        leading=9.5,
        textColor=colors.HexColor("#0F172A"),
        fontName="Helvetica-Bold",
        alignment=2,
    )

    story = []

    # 1. Header Row: Seller details on left, TAX INVOICE title on right
    invoice_num = sale.invoice_number or sale.sale_number
    date_str = sale.created_at.strftime("%d-%b-%Y %I:%M %p")

    seller_address = f"{biz_settings.address_line1}"
    if biz_settings.address_line2:
        seller_address += f", {biz_settings.address_line2}"
    seller_address += f", {biz_settings.city}, {biz_settings.state} - {biz_settings.pincode}"

    seller_html = (
        f"<b>{biz_settings.name}</b><br/>"
        f"<font size=7.5 color='#475569'>{seller_address}<br/>"
        f"GSTIN: <b>{biz_settings.gstin}</b> | State: {biz_settings.state}<br/>"
        f"Email: {biz_settings.email} | Phone: {biz_settings.phone}<br/>"
        f"Warehouse: {sale.warehouse.name} ({sale.warehouse.code})</font>"
    )

    invoice_meta_html = (
        f"<font size=16 color='#1E3A8A'><b>TAX INVOICE</b></font><br/>"
        f"<font size=8 color='#475569'><b>Invoice No:</b> <font color='#0F172A'>{invoice_num}</font><br/>"
        f"<b>Date:</b> <font color='#0F172A'>{date_str}</font><br/>"
        f"<b>Place of Supply:</b> <font color='#0F172A'>{sale.place_of_supply or biz_settings.state}</font><br/>"
        f"<b>Supply Type:</b> <font color='#0F172A'>{'Inter-State (IGST)' if is_interstate else 'Intra-State (CGST + SGST)'}</font></font>"
    )

    header_table = Table(
        [[Paragraph(seller_html, meta_val), Paragraph(invoice_meta_html, meta_val)]],
        colWidths=[310, 230],
    )
    header_table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("ALIGN", (1, 0), (1, 0), "RIGHT"),
        ("TOPPADDING", (0, 0), (-1, -1), 0),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(header_table)

    story.append(Spacer(1, 6))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#CBD5E1"), spaceAfter=6))

    # 2. Buyer Details Row
    if customer:
        cust_name = customer.name
        cust_phone = customer.phone
        cust_addr = customer.address or "N/A"
        cust_gstin = sale.customer_gstin or customer.gstin or "Unregistered / Consumer"
    else:
        cust_name = "Walk-in Retail Customer"
        cust_phone = "N/A"
        cust_addr = "N/A"
        cust_gstin = sale.customer_gstin or "Unregistered / Consumer"

    buyer_html = (
        f"<b>Bill To (Customer Details):</b><br/>"
        f"<font size=7.5 color='#334155'><b>Name:</b> {cust_name}<br/>"
        f"<b>Phone:</b> {cust_phone} | <b>GSTIN:</b> {cust_gstin}<br/>"
        f"<b>Address:</b> {cust_addr}</font>"
    )
    buyer_table = Table([[Paragraph(buyer_html, meta_val)]], colWidths=[540])
    buyer_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ("PADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(buyer_table)
    story.append(Spacer(1, 8))

    # 3. Itemized Products Table
    if is_interstate:
        headers = ["#", "Item Description", "HSN/SAC", "Qty", "Rate (₹)", "Taxable (₹)", "IGST Rate", "IGST (₹)", "Total (₹)"]
        col_widths = [20, 150, 45, 30, 50, 60, 45, 55, 65]
    else:
        headers = ["#", "Item Description", "HSN/SAC", "Qty", "Rate (₹)", "Taxable (₹)", "CGST (₹)", "SGST (₹)", "Total (₹)"]
        col_widths = [20, 150, 45, 30, 50, 60, 50, 50, 65]

    item_rows = [[Paragraph(h, table_header) for h in headers]]

    for idx, line in enumerate(sale.lines.all(), 1):
        line_tot = (line.taxable_amount + line.tax_amount).quantize(Decimal("0.01"))
        desc = f"<b>{line.product.name}</b><br/><font size=6.5 color='#64748B'>SKU: {line.product.sku}</font>"
        hsn = line.hsn_code or "—"
        rate = f"{line.unit_price:.2f}"
        taxable = f"{line.taxable_amount:.2f}"

        if is_interstate:
            igst_str = f"{line.igst_amount:.2f}"
            row = [
                Paragraph(str(idx), table_cell),
                Paragraph(desc, table_cell),
                Paragraph(hsn, table_cell),
                Paragraph(str(line.quantity), table_cell_right),
                Paragraph(rate, table_cell_right),
                Paragraph(taxable, table_cell_right),
                Paragraph(f"{line.gst_rate:.1f}%", table_cell_right),
                Paragraph(igst_str, table_cell_right),
                Paragraph(f"{line_tot:.2f}", table_cell_right_bold),
            ]
        else:
            cgst_str = f"{line.cgst_amount:.2f}"
            sgst_str = f"{line.sgst_amount:.2f}"
            row = [
                Paragraph(str(idx), table_cell),
                Paragraph(desc, table_cell),
                Paragraph(hsn, table_cell),
                Paragraph(str(line.quantity), table_cell_right),
                Paragraph(rate, table_cell_right),
                Paragraph(taxable, table_cell_right),
                Paragraph(cgst_str, table_cell_right),
                Paragraph(sgst_str, table_cell_right),
                Paragraph(f"{line_tot:.2f}", table_cell_right_bold),
            ]
        item_rows.append(row)

    items_table = Table(item_rows, colWidths=col_widths, repeatRows=1)
    items_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1E3A8A")),
        ("ALIGN", (0, 0), (-1, 0), "CENTER"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
        ("PADDING", (0, 0), (-1, -1), 4),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
    ]))
    story.append(items_table)
    story.append(Spacer(1, 8))

    # 4. HSN Summary & Financial Totals side by side
    # Compute HSN Summary
    hsn_dict: Dict[str, Dict[str, Any]] = {}
    for line in sale.lines.all():
        key = f"{line.hsn_code or 'General'}_{line.gst_rate}"
        if key not in hsn_dict:
            hsn_dict[key] = {
                "hsn": line.hsn_code or "General",
                "rate": line.gst_rate,
                "taxable": Decimal("0.00"),
                "cgst": Decimal("0.00"),
                "sgst": Decimal("0.00"),
                "igst": Decimal("0.00"),
                "tax": Decimal("0.00"),
            }
        hsn_dict[key]["taxable"] += line.taxable_amount
        hsn_dict[key]["cgst"] += line.cgst_amount
        hsn_dict[key]["sgst"] += line.sgst_amount
        hsn_dict[key]["igst"] += line.igst_amount
        hsn_dict[key]["tax"] += line.tax_amount

    if is_interstate:
        hsn_headers = ["HSN/SAC", "Taxable (₹)", "IGST %", "IGST (₹)", "Total Tax (₹)"]
        hsn_widths = [55, 65, 45, 55, 60]
    else:
        hsn_headers = ["HSN/SAC", "Taxable (₹)", "CGST (₹)", "SGST (₹)", "Total Tax (₹)"]
        hsn_widths = [55, 65, 50, 50, 60]

    hsn_table_rows = [[Paragraph(h, table_header) for h in hsn_headers]]
    for item in hsn_dict.values():
        if is_interstate:
            hsn_table_rows.append([
                Paragraph(item["hsn"], table_cell),
                Paragraph(f"{item['taxable']:.2f}", table_cell_right),
                Paragraph(f"{item['rate']:.1f}%", table_cell_right),
                Paragraph(f"{item['igst']:.2f}", table_cell_right),
                Paragraph(f"{item['tax']:.2f}", table_cell_right_bold),
            ])
        else:
            hsn_table_rows.append([
                Paragraph(item["hsn"], table_cell),
                Paragraph(f"{item['taxable']:.2f}", table_cell_right),
                Paragraph(f"{item['cgst']:.2f}", table_cell_right),
                Paragraph(f"{item['sgst']:.2f}", table_cell_right),
                Paragraph(f"{item['tax']:.2f}", table_cell_right_bold),
            ])

    hsn_table = Table(hsn_table_rows, colWidths=hsn_widths)
    hsn_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#334155")),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
        ("PADDING", (0, 0), (-1, -1), 3),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
    ]))

    # Totals breakdown table
    totals_rows = [
        [Paragraph("Subtotal (Gross):", meta_label), Paragraph(f"₹{sale.subtotal:.2f}", table_cell_right)],
    ]
    if sale.discount_amount > Decimal("0.00"):
        disc_label = f"Discount ({sale.discount_type.capitalize()}):"
        totals_rows.append([Paragraph(disc_label, meta_label), Paragraph(f"-₹{sale.discount_amount:.2f}", table_cell_right)])

    totals_rows.append([Paragraph("Taxable Amount:", meta_label), Paragraph(f"₹{sale.taxable_amount:.2f}", table_cell_right)])

    if is_interstate:
        totals_rows.append([Paragraph("Total IGST:", meta_label), Paragraph(f"₹{sale.igst_amount:.2f}", table_cell_right)])
    else:
        totals_rows.append([Paragraph("Total CGST:", meta_label), Paragraph(f"₹{sale.cgst_amount:.2f}", table_cell_right)])
        totals_rows.append([Paragraph("Total SGST:", meta_label), Paragraph(f"₹{sale.sgst_amount:.2f}", table_cell_right)])

    if sale.round_off_amount != Decimal("0.00"):
        sign = "+" if sale.round_off_amount > 0 else ""
        totals_rows.append([Paragraph("Round Off:", meta_label), Paragraph(f"₹{sign}{sale.round_off_amount:.2f}", table_cell_right)])

    totals_rows.append([
        Paragraph("<b>Grand Total:</b>", ParagraphStyle("GTLabel", parent=meta_label, fontSize=9, textColor=colors.HexColor("#0F172A"))),
        Paragraph(f"<b>₹{sale.total_amount:.2f}</b>", ParagraphStyle("GTVal", parent=table_cell_right_bold, fontSize=10, textColor=colors.HexColor("#1E3A8A"))),
    ])

    if sale.payment_method == "credit" or sale.balance_due > Decimal("0.00"):
        totals_rows.append([Paragraph("Amount Paid:", meta_label), Paragraph(f"₹{sale.amount_paid:.2f}", table_cell_right)])
        totals_rows.append([
            Paragraph("<b>Balance Due:</b>", meta_label),
            Paragraph(f"<b>₹{sale.balance_due:.2f}</b>", ParagraphStyle("DueVal", parent=table_cell_right_bold, textColor=colors.HexColor("#DC2626"))),
        ])

    totals_table = Table(totals_rows, colWidths=[130, 110])
    totals_table.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ("PADDING", (0, 0), (-1, -1), 3),
        ("BACKGROUND", (0, -1), (-1, -1), colors.HexColor("#F1F5F9")),
    ]))

    # Wrap HSN Table and Totals in two columns
    summary_wrapper = Table(
        [[
            Paragraph("<b>HSN / SAC Tax Breakup</b>", ParagraphStyle("HsnTitle", parent=meta_label, spaceAfter=4)),
            Paragraph("<b>Invoice Calculation</b>", ParagraphStyle("TotTitle", parent=meta_label, spaceAfter=4)),
        ],
        [hsn_table, totals_table]],
        colWidths=[280, 260],
    )
    summary_wrapper.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
    ]))
    story.append(summary_wrapper)
    story.append(Spacer(1, 8))

    # 5. Amount in Words Box
    words = amount_to_words_inr(sale.total_amount)
    words_html = f"<b>Total Invoice Amount in Words:</b><br/><font size=8 color='#1E293B'><i>{words}</i></font>"
    words_table = Table([[Paragraph(words_html, meta_val)]], colWidths=[540])
    words_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
        ("PADDING", (0, 0), (-1, -1), 5),
    ]))
    story.append(words_table)
    story.append(Spacer(1, 10))

    # 6. Terms & Signature Block
    terms_html = (
        "<b>Terms & Conditions:</b><br/>"
        "<font size=6.5 color='#64748B'>"
        "1. Goods once sold will be accepted for exchange/return strictly within store policy.<br/>"
        "2. All disputes are subject to local jurisdiction.<br/>"
        "3. This is a computer-generated tax invoice and requires no physical seal if authorized digitally."
        "</font>"
    )
    sign_html = (
        f"<font size=7.5 color='#475569'>For <b>{biz_settings.name}</b></font><br/><br/><br/>"
        "<font size=7 color='#64748B'>Authorized Signatory</font>"
    )
    footer_table = Table(
        [[Paragraph(terms_html, meta_val), Paragraph(sign_html, ParagraphStyle("SignAlign", parent=meta_val, alignment=2))]],
        colWidths=[360, 180],
    )
    footer_table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ("PADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(footer_table)

    doc.build(story, canvasmaker=InvoiceNumberedCanvas)
    return buffer.getvalue()
